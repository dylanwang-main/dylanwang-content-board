// Generates supabase/migrations/0001_init.sql from the Base44 entity definitions
// in base44/entities/*.jsonc, so the Postgres schema stays traceable to the
// original data model. Run: node scripts/gen-schema.mjs
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, basename } from 'node:path';

const ENTITY_DIR = 'base44/entities';
const OUT = 'supabase/migrations/0001_init.sql';

// Entity name -> Postgres table name. Shared with src/api/tables.js.
export const TABLES = {
  BrainFile: 'brain_files',
  Brand: 'brands',
  ContentItem: 'content_items',
  ContentScan: 'content_scans',
  Research: 'research',
  Outlier: 'outliers',
  SocialAccount: 'social_accounts',
  InstagramMedia: 'instagram_media',
  TikTokMedia: 'tiktok_media',
  YouTubeVideo: 'youtube_videos',
};

const PG_TYPE = {
  string: 'text',
  number: 'double precision',
  boolean: 'boolean',
  object: 'jsonb',
  array: 'jsonb',
};

const stripComments = (s) => s.replace(/^\s*\/\/.*$/gm, '');
const lit = (v) =>
  typeof v === 'string' ? `'${v.replace(/'/g, "''")}'` : typeof v === 'object' ? `'${JSON.stringify(v)}'::jsonb` : String(v);

function tableSql(entity, def) {
  const table = TABLES[entity];
  const required = new Set(def.required || []);
  const cols = [
    'id uuid primary key default gen_random_uuid()',
    'created_by_id uuid not null default auth.uid() references auth.users (id) on delete cascade',
    'created_date timestamptz not null default now()',
    'updated_date timestamptz not null default now()',
  ];
  for (const [name, p] of Object.entries(def.properties || {})) {
    const type = PG_TYPE[p.type];
    if (!type) throw new Error(`${entity}.${name}: unsupported type ${p.type}`);
    let col = `${name} ${type}`;
    if (p.default !== undefined) col += ` default ${lit(p.default)}`;
    if (required.has(name)) col += ' not null';
    if (p.enum) col += ` check (${name} in (${p.enum.map(lit).join(', ')}))`;
    cols.push(col);
  }
  return `-- ${entity}
create table public.${table} (
  ${cols.join(',\n  ')}
);
create index ${table}_owner_created_idx on public.${table} (created_by_id, created_date desc);
create trigger ${table}_touch before update on public.${table}
  for each row execute function public.touch_updated_date();
alter table public.${table} enable row level security;
grant select, insert, update, delete on public.${table} to authenticated;
create policy "${table}_own_select" on public.${table} for select using (created_by_id = auth.uid());
create policy "${table}_own_insert" on public.${table} for insert with check (created_by_id = auth.uid());
create policy "${table}_own_update" on public.${table} for update using (created_by_id = auth.uid()) with check (created_by_id = auth.uid());
create policy "${table}_own_delete" on public.${table} for delete using (created_by_id = auth.uid());
`;
}

const header = `-- Generated by scripts/gen-schema.mjs from base44/entities/*.jsonc. Do not edit by hand.
-- Every table is private to its owner via row-level security (created_by_id = auth.uid()),
-- matching the Base44 rule "read/update/delete where created_by_id = user.id".

create or replace function public.touch_updated_date() returns trigger
language plpgsql as $$
begin
  new.updated_date = now();
  return new;
end $$;

-- Replaces Base44's built-in User entity custom fields (auth.me / auth.updateMe).
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  full_name text,
  display_name text,
  monthly_goal double precision,
  platforms jsonb,
  logo_url text,
  youtube_handle text,
  roadmap jsonb,
  milestone_overrides jsonb,
  created_date timestamptz not null default now(),
  updated_date timestamptz not null default now()
);
create trigger profiles_touch before update on public.profiles
  for each row execute function public.touch_updated_date();
alter table public.profiles enable row level security;
-- Explicit grants: works whether or not "Automatically expose new tables" is on.
-- Only signed-in users get access; the anon role gets nothing.
grant select, insert, update on public.profiles to authenticated;
create policy "profiles_own_select" on public.profiles for select using (id = auth.uid());
create policy "profiles_own_insert" on public.profiles for insert with check (id = auth.uid());
create policy "profiles_own_update" on public.profiles for update using (id = auth.uid()) with check (id = auth.uid());

-- Create a profile row automatically when someone signs up.
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, new.raw_user_meta_data ->> 'full_name')
  on conflict (id) do nothing;
  return new;
end $$;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- Private storage bucket for Brain uploads; each user reads/writes only their own folder.
insert into storage.buckets (id, name, public) values ('brain', 'brain', false)
  on conflict (id) do nothing;
create policy "brain_own_objects" on storage.objects for all
  using (bucket_id = 'brain' and (storage.foldername(name))[1] = auth.uid()::text)
  with check (bucket_id = 'brain' and (storage.foldername(name))[1] = auth.uid()::text);
`;

const files = readdirSync(ENTITY_DIR).filter((f) => f.endsWith('.jsonc') && f !== 'User.jsonc');
const parts = [header];
for (const f of files.sort()) {
  const entity = basename(f, '.jsonc');
  if (!TABLES[entity]) throw new Error(`No table mapping for entity ${entity}`);
  const def = JSON.parse(stripComments(readFileSync(join(ENTITY_DIR, f), 'utf8')));
  parts.push(tableSql(entity, def));
}
mkdirSync('supabase/migrations', { recursive: true });
writeFileSync(OUT, parts.join('\n'));
console.log(`Wrote ${OUT} (${files.length} tables + profiles)`);
